// Package webport校验用于浏览器访问的HTTP(S)外部端口。
package webport

import "fmt"

// Validate依据WHATWG Fetch的Port blocking表，避免TCP可监听但浏览器拒绝访问。
// 资料：https://fetch.spec.whatwg.org/#port-blocking，核对日期2026-11-03。
// 不对仅供反向代理使用的内部监听端口应用此表。
func Validate(port int) error {
	if port < 1 || port > 65535 {
		return fmt.Errorf("端口必须是1～65535的整数")
	}
	switch port {
	case 1, 7, 9, 11, 13, 15, 17, 19, 20, 21, 22, 23, 25, 37, 42, 43, 53, 69, 77, 79, 87, 95,
		101, 102, 103, 104, 109, 110, 111, 113, 115, 117, 119, 123, 135, 137, 139, 143, 161, 179,
		389, 427, 465, 512, 513, 514, 515, 526, 530, 531, 532, 540, 548, 554, 556, 563, 587, 601,
		636, 989, 990, 993, 995, 1719, 1720, 1723, 2049, 3659, 4045, 4190, 5060, 5061, 6000,
		6566, 6665, 6666, 6667, 6668, 6669, 6679, 6697, 10080:
		return fmt.Errorf("端口%d被浏览器禁止访问，请选择8080、9000或10081等其他端口", port)
	}
	return nil
}
